export function shuffle(list) {
  const out = [...list];
  for (let i = out.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
}

export function randomRoomCode() {
  const chars = 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';
  let code = 'S';
  for (let i = 0; i < 5; i++) code += chars[Math.floor(Math.random() * chars.length)];
  return code;
}

export function pickLocation(deck = LOCATIONS) {
  if (!deck.length) throw new Error('ไม่มีสถานที่ในชุดเกม');
  return deck[Math.floor(Math.random() * deck.length)];
}

export function assignRound(playerEntries, location) {
  if (playerEntries.length < 3) throw new Error('ต้องมีผู้เล่นอย่างน้อย 3 คน');
  const shuffled = shuffle(playerEntries);
  const spyUid = shuffled[0][0];
  const roles = shuffle(location.roles);
  const assignments = {};
  let roleIndex = 0;
  for (const [uid] of shuffled) {
    if (uid === spyUid) {
      assignments[uid] = { isSpy: true, role: 'SPY', location: null };
    } else {
      assignments[uid] = { isSpy: false, role: roles[roleIndex % roles.length], location: location.name };
      roleIndex += 1;
    }
  }
  return { spyUid, assignments };
}

export function escapeHtml(value) {
  return String(value ?? '').replace(/[&<>"']/g, ch => ({
    '&':'&amp;', '<':'&lt;', '>':'&gt;', '"':'&quot;', "'":'&#039;'
  })[ch]);
}
